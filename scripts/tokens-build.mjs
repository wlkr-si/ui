// Generates the token CSS and the `theme` registry item from lib/tokens.ts, the only place token values are written.
import { readFile, writeFile } from "node:fs/promises"
import { colour, flat, ramps, shadcnAliases } from "../lib/tokens.ts"

const themed = value => typeof value === "object"
const pick = (value, mode) => themed(value) ? value[mode] : value

const primitives = Object.fromEntries(ramps.flatMap(ramp => ramp.steps.map(([step, hex]) => [`wlkr-${ramp.name}-${step}`, hex])))
const fixed = Object.fromEntries(flat.filter(token => !themed(token.value)).map(token => [`wlkr-${token.name}`, token.value]))
// Semantic colour and themed scales are declared in every theme scope, so a nested light or dark panel recomputes them.
const scoped = [...colour.flatMap(group => group.tokens), ...flat.filter(token => themed(token.value))]
const modeVars = mode => ({
  ...Object.fromEntries(scoped.map(token => [`wlkr-${token.name}`, pick(token.value, mode)])),
  ...Object.fromEntries(Object.entries(shadcnAliases).map(([alias, target]) => [alias, `var(--wlkr-${target})`])),
  radius: ".375rem",
})
const colourNames = colour.flatMap(group => group.tokens.map(token => token.name))
const tailwind = Object.fromEntries(colourNames.map(name => [`color-${name}`, `var(--wlkr-${name})`]))

const block = (selector, vars) => `${selector} {\n${Object.entries(vars).map(([name, value]) => `  --${name}: ${value};`).join("\n")}\n}`
const css = [
  "/* Generated by scripts/tokens-build.mjs from lib/tokens.ts. Do not edit. */",
  block(":root", { ...primitives, ...fixed }),
  block(":root, .wlkr-light", modeVars("light")),
  block(".dark, .wlkr-dark", modeVars("dark")),
  `.wlkr-light { color-scheme: light; }\n.dark, .wlkr-dark { color-scheme: dark; }`,
  block("@theme inline", tailwind),
].join("\n\n") + "\n"
await writeFile("registry/wlkr/tokens.css", css)

const registry = JSON.parse(await readFile("registry.json", "utf8"))
const theme = registry.items.find(item => item.name === "theme")
if (!theme) throw new Error("registry.json has no theme item to fill.")
theme.description = "The WLKR design tokens: neutral and brand primitives, semantic light and dark roles, and the control, type, space, radius, elevation and motion scales, with shadcn/ui aliases."
const { radius, ...darkVars } = modeVars("dark")
void radius
theme.cssVars = {
  theme: { ...tailwind, "color-brand-foreground": "var(--brand-foreground)" },
  light: { ...primitives, ...fixed, ...modeVars("light") },
  dark: darkVars,
}
await writeFile("registry.json", JSON.stringify(registry, null, 2) + "\n")
console.log(`tokens: ${Object.keys(primitives).length} primitives, ${Object.keys(fixed).length} scale values, ${scoped.length} themed tokens.`)
