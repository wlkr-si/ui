// Rebuilds the component entries of registry.json from registry/meta/*.ts, the catalog's single source.
// Items without a meta-driven entry (the theme and typography styles) are kept exactly as written.
import { readdir, readFile, writeFile } from "node:fs/promises"
import { pathToFileURL } from "node:url"
import { categories } from "../lib/component-meta.ts"

const registry = JSON.parse(await readFile("registry.json", "utf8"))
const rank = new Map(categories.map((category, index) => [category.id, index]))
const slugs = (await readdir("registry/meta")).filter(file => file.endsWith(".ts")).map(file => file.slice(0, -3))
const entries = await Promise.all(slugs.map(async slug => ({ slug, ...(await import(pathToFileURL(`registry/meta/${slug}.ts`).href)).meta })))
entries.sort((a, b) => (rank.get(a.category) ?? 99) - (rank.get(b.category) ?? 99) || (a.order ?? 1000) - (b.order ?? 1000) || a.name.localeCompare(b.name))

const generated = entries.filter(entry => entry.registry !== false).map(entry => ({
  name: entry.slug,
  type: "registry:component",
  title: entry.name,
  description: entry.summary,
  author: "WLKR Labs",
  ...(entry.dependencies?.length ? { dependencies: entry.dependencies } : {}),
  ...(entry.registryDependencies?.length ? { registryDependencies: entry.registryDependencies } : {}),
  files: [{ path: `registry/wlkr/${entry.slug}.tsx`, type: "registry:component", target: `components/wlkr/${entry.slug}.tsx` }, ...(entry.files ?? [])],
}))
const names = new Set(generated.map(item => item.name))
const kept = registry.items.filter(item => !names.has(item.name))
for (const item of kept) if (item.type === "registry:component") throw new Error(`registry.json lists "${item.name}" but registry/meta/${item.name}.ts is missing.`)

// Explicit imports: the site reads these two files instead of discovering modules at runtime.
const pascal = slug => slug.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join("")
const banner = "// Generated by scripts/registry-sync.mjs from registry/meta. Do not edit.\n"
await writeFile("lib/catalog-metas.ts", `${banner}import type { ComponentMeta } from "./component-meta"\n${entries.map((entry, index) => `import { meta as m${index} } from "@/registry/meta/${entry.slug}"`).join("\n")}\n\nexport const metas: [slug: string, meta: ComponentMeta][] = [\n${entries.map((entry, index) => `  ["${entry.slug}", m${index}],`).join("\n")}\n]\n`)
await writeFile("lib/catalog-demos.ts", `${banner}import type { ComponentType } from "react"\n${entries.map(entry => `import { ${pascal(entry.slug)}Demo } from "@/components/demos/${entry.slug}-demo"`).join("\n")}\n\nexport const demos: Record<string, ComponentType> = {\n${entries.map(entry => `  "${entry.slug}": ${pascal(entry.slug)}Demo,`).join("\n")}\n}\n`)

registry.items = [...generated, ...kept]
await writeFile("registry.json", JSON.stringify(registry, null, 2) + "\n")
console.log(`registry.json: ${generated.length} components from the catalog, ${kept.length} kept as written.`)
